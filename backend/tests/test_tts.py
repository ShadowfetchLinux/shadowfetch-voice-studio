def test_compare_engines_sequential(tmp_path, monkeypatch):
    install_fake_audio(monkeypatch)
    eng = FakeEngineManager([fake_caps("engine-a"), fake_caps("engine-b", supports_reusable_prompt=False)])
    server = make_server(tmp_path, eng)
    v = make_voice(server)
    p = call(server, "projects.create", {"name": "Cmp", "voice_id": v["id"], "script_text": "One. Two."})
    call(server, "tts.plan", {"project_id": p["id"], "engine_id": "engine-a"})
    res = call(server, "tts.compare_engines", {"project_id": p["id"], "engine_ids": ["engine-a", "engine-b", "engine-x"], "segment_index": 0,
                                               "settings": {"engine-b": {"temperature": 0.5}}})
    ok = [r for r in res["results"] if "error" in r]
    assert [r["engine_id"] for r in res["results"]] == ["engine-a", "engine-b", "engine-x"] and ok[0]["engine_id"] == "engine-x"
    assert eng.load_order == ["engine-a", "engine-b"]
    for r in res["results"][:2]:
        assert Path(r["path"]).exists() and Path(r["loudness_matched_preview_path"]).exists()
        assert Path(r["loudness_matched_preview_path"]).parent == server.state["paths"].tmp
    assert eng.calls[1]["settings"] == {"temperature": 0.5} and eng.calls[0]["settings"] == {}
    # generated takes are stored but not auto-selected; originals untouched by the preview copy
    seg = call(server, "projects.get", {"id": p["id"]})["segments"][0]
    assert len(seg["takes"]) == 2 and seg["selected_take_id"] is None and {t["label"] for t in seg["takes"]} == {"compare:engine-a", "compare:engine-b"}
    assert Path(res["results"][0]["path"]).read_bytes() == Path(res["results"][0]["loudness_matched_preview_path"]).read_bytes()
