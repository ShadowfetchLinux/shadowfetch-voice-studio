# ---------------------------------------------------------------- assemble
def test_assemble_master(server):
    v, p, plan = make_project(server)
    with pytest.raises(WorkerError) as ei:
        call(server, "tts.assemble", {"project_id": p["id"]})
    assert ei.value.code == INVALID_PARAMS and ei.value.details["missing_segments"] == [0, 1, 2, 3]
    gen = call(server, "tts.generate", {"project_id": p["id"]})
    res = call(server, "tts.assemble", {"project_id": p["id"], "sentence_pause_ms": 100, "paragraph_pause_ms": 500})
    master = Path(res["master_path"])
    assert master.name == "master.wav" and master.exists() and res["segments_used"] == 4 and res["sample_rate"] == 24000
    takes_total = sum(t["duration_s"] for t in gen["takes"])
    expected = takes_total + 2 * 0.1 + 0.5
    assert abs(res["duration_s"] - expected) < 0.02 and abs(sf.info(str(master)).duration - expected) < 0.02
    proj = call(server, "projects.get", {"id": p["id"]})["project"]
    assert proj["master_path"] == str(master) and proj["master"]["take_ids"] == [t["take_id"] for t in gen["takes"]]
    assert proj["settings"]["plan"]["sentence_pause_ms"] == 100
    # explicit take selection override + a stale id is rejected
    alt = call(server, "tts.generate", {"project_id": p["id"], "segment_indices": [0]})["takes"][0]
    res2 = call(server, "tts.assemble", {"project_id": p["id"], "take_selection": {"0": gen["takes"][0]["take_id"]}})
    assert call(server, "projects.get", {"id": p["id"]})["project"]["master"]["take_ids"][0] == gen["takes"][0]["take_id"] != alt["take_id"]
    with pytest.raises(WorkerError):
        call(server, "tts.assemble", {"project_id": p["id"], "take_selection": {"1": "take_nope"}})
    assert res2["segments_used"] == 4 and not (master.parent / "master.tmp.wav").exists()


