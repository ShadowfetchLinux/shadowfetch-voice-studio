def test_cancel_mid_run_keeps_completed_takes(tmp_path, monkeypatch):
    install_fake_audio(monkeypatch)
    eng = FakeEngineManager(cancel_after=2)
    server = make_server(tmp_path, eng)
    v, p, plan = make_project(server)
    ctx = make_ctx(server, "tts.generate")
    with pytest.raises(CancelledError) as ei:
        call(server, "tts.generate", {"project_id": p["id"]}, ctx=ctx)
    err = ei.value
    assert err.code == CANCELLED and len(err.details["completed"]) == 2 and err.details["failed_segment"] == 2
    assert len(eng.calls) == 2
    view = call(server, "projects.get", {"id": p["id"]})
    assert [len(s["takes"]) for s in view["segments"]] == [1, 1, 0, 0]
    assert all(Path(t["path"]).exists() for t in err.details["completed"])
    # resuming generates only the two missing segments
    eng.cancel_after = None
    res = call(server, "tts.generate", {"project_id": p["id"]})
    assert [t["segment_index"] for t in res["takes"]] == [2, 3] and res["skipped"] == [0, 1]


